//! Generates `.claude/skills/atlassian-cli/reference.md`, the full command
//! reference used by the Agent Skill, from the clap definitions, and fails if
//! the committed file is out of date.
//!
//! Regenerate with: `UPDATE_REFERENCE=1 cargo test --test reference`

use std::fmt::Write as _;
use std::path::Path;

use atlassian_cli::Cli;
use clap::{Arg, ArgAction, Command, CommandFactory, Parser};

const REFERENCE: &str = ".claude/skills/atlassian-cli/reference.md";
const SKILL: &str = ".claude/skills/atlassian-cli/SKILL.md";

/// Global options that point the CLI at a server or credentials. People set
/// these up; the agent using the skill must not, so the reference leaves
/// them out (they are still in `--help` and the README).
const CONFIG_ARGS: &[&str] = &["config", "base_url", "ca_cert"];

/// Help text on one line, safe inside a Markdown table cell.
fn cell(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

fn help(arg: &Arg) -> String {
    arg.get_long_help()
        .or_else(|| arg.get_help())
        .map(|h| h.to_string())
        .unwrap_or_default()
}

fn about(cmd: &Command) -> String {
    cmd.get_about().map(|a| a.to_string()).unwrap_or_default()
}

fn value_names(arg: &Arg) -> String {
    match arg.get_value_names() {
        Some(names) => names
            .iter()
            .map(|n| n.to_string())
            .collect::<Vec<_>>()
            .join(" "),
        None => arg.get_id().as_str().to_uppercase(),
    }
}

/// How an argument is written on the command line, e.g. `--state <STATE>`.
fn usage(arg: &Arg) -> String {
    if arg.is_positional() {
        let name = value_names(arg);
        return if arg.is_required_set() {
            format!("<{name}>")
        } else {
            format!("[{name}]")
        };
    }
    let mut flag = String::new();
    if let Some(short) = arg.get_short() {
        write!(flag, "-{short}, ").unwrap();
    }
    write!(
        flag,
        "--{}",
        arg.get_long().expect("options have a long name")
    )
    .unwrap();
    if !matches!(arg.get_action(), ArgAction::SetTrue | ArgAction::SetFalse) {
        write!(flag, " <{}>", value_names(arg)).unwrap();
    }
    flag
}

/// Required/default/possible-values/repeatable notes for an argument.
fn notes(arg: &Arg) -> String {
    let mut notes = Vec::new();
    if arg.is_required_set() && !arg.is_positional() {
        notes.push("required".to_string());
    }
    let defaults: Vec<String> = arg
        .get_default_values()
        .iter()
        .map(|v| v.to_string_lossy().into_owned())
        .collect();
    if !defaults.is_empty() {
        notes.push(format!("default: `{}`", defaults.join(",")));
    }
    let values: Vec<String> = arg
        .get_possible_values()
        .iter()
        .filter(|v| !v.is_hide_set())
        .map(|v| format!("`{}`", v.get_name()))
        .collect();
    let is_flag = matches!(arg.get_action(), ArgAction::SetTrue | ArgAction::SetFalse);
    if !values.is_empty() && !is_flag {
        notes.push(format!("one of {}", values.join(", ")));
    }
    if matches!(arg.get_action(), ArgAction::Append) {
        notes.push("repeatable".to_string());
    }
    if notes.is_empty() {
        String::new()
    } else {
        format!(" ({})", notes.join("; "))
    }
}

fn arg_table(out: &mut String, args: &[&Arg]) {
    if args.is_empty() {
        out.push_str("No arguments or options.\n\n");
        return;
    }
    out.push_str("| Argument / option | Description |\n|---|---|\n");
    for arg in args {
        writeln!(
            out,
            "| `{}` | {}{} |",
            usage(arg),
            cell(&help(arg)),
            notes(arg)
        )
        .unwrap();
    }
    out.push('\n');
}

fn is_shown(arg: &Arg) -> bool {
    let id = arg.get_id().as_str();
    !arg.is_hide_set() && !arg.is_global_set() && id != "help" && id != "version"
}

fn leaves(cmd: &Command, path: &str, out: &mut String) {
    for sub in cmd.get_subcommands() {
        if sub.get_name() == "help" || sub.is_hide_set() {
            continue;
        }
        let sub_path = format!("{path} {}", sub.get_name());
        if sub.has_subcommands() {
            leaves(sub, &sub_path, out);
            continue;
        }
        writeln!(out, "### `atlassian{sub_path}`\n\n{}\n", cell(&about(sub))).unwrap();
        let args: Vec<&Arg> = sub.get_arguments().filter(|a| is_shown(a)).collect();
        arg_table(out, &args);
    }
}

fn render() -> String {
    let cli = Cli::command();
    let mut out = String::new();
    out.push_str(
        "# `atlassian` command reference\n\n\
         <!-- Generated by tests/reference.rs from the clap definitions; do not edit by hand.\n     \
         Regenerate with: UPDATE_REFERENCE=1 cargo test --test reference -->\n\n\
         Every command only reads data (HTTP GET). Commands are\n\
         `atlassian <product> <resource> <action>`; run any of them with `--help` for the same\n\
         information.\n\n",
    );

    out.push_str("## Global options\n\nAccepted by every command, before or after it.\n\n");
    let globals: Vec<&Arg> = cli
        .get_arguments()
        .filter(|a| {
            a.is_global_set() && !a.is_hide_set() && !CONFIG_ARGS.contains(&a.get_id().as_str())
        })
        .collect();
    arg_table(&mut out, &globals);

    for product in cli.get_subcommands() {
        if product.get_name() == "help" {
            continue;
        }
        let aliases: Vec<&str> = product.get_visible_aliases().collect();
        let alias_note = if aliases.is_empty() {
            String::new()
        } else {
            format!(" (alias: `{}`)", aliases.join("`, `"))
        };
        writeln!(
            out,
            "## `{}`{alias_note}\n\n{}\n",
            product.get_name(),
            cell(&about(product))
        )
        .unwrap();
        leaves(product, &format!(" {}", product.get_name()), &mut out);
    }
    out.trim_end().to_string() + "\n"
}

#[test]
fn reference_is_up_to_date() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(REFERENCE);
    let expected = render();
    if std::env::var_os("UPDATE_REFERENCE").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &expected).unwrap();
        return;
    }
    let actual = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        actual == expected,
        "{REFERENCE} is out of date with the CLI definition.\n\
         Regenerate it with: UPDATE_REFERENCE=1 cargo test --test reference"
    );
}

/// Split a shell command line into words, honouring single and double quotes.
/// Stops at an unquoted `|`, so piped commands keep only their first part.
fn shell_words(line: &str) -> Vec<String> {
    let mut words = Vec::new();
    let mut word = String::new();
    let mut in_word = false;
    let mut quote: Option<char> = None;
    for c in line.chars() {
        match (quote, c) {
            (Some(q), c) if c == q => quote = None,
            (Some(_), c) => word.push(c),
            (None, '\'' | '"') => {
                quote = Some(c);
                in_word = true;
            }
            (None, '|') => break,
            (None, c) if c.is_whitespace() => {
                if in_word {
                    words.push(std::mem::take(&mut word));
                    in_word = false;
                }
            }
            (None, c) => {
                word.push(c);
                in_word = true;
            }
        }
    }
    if in_word {
        words.push(word);
    }
    words
}

/// Every `atlassian ...` example in SKILL.md must parse with the real CLI,
/// so the skill can't teach commands or options that don't exist.
#[test]
fn skill_examples_parse() {
    let skill = read(SKILL);
    // Placeholders such as <boardId> stand for real values.
    let placeholder = regex::Regex::new(r"<[A-Za-z]+>").unwrap();
    let mut checked = 0;
    let mut failures = Vec::new();
    // Inline code spans: the text between pairs of backticks.
    for span in skill.split('`').skip(1).step_by(2) {
        if !span.starts_with("atlassian ") || span.contains("<product>") {
            continue;
        }
        // Inside Markdown tables, `\|` is a literal pipe.
        let example = placeholder
            .replace_all(&span.replace("\\|", "|"), "1")
            .into_owned();
        let words = shell_words(&example);
        match Cli::try_parse_from(&words) {
            Ok(_) => {}
            Err(e) if e.kind() == clap::error::ErrorKind::DisplayHelp => {}
            Err(e) => failures.push(format!("`{span}`: {}", e.kind())),
        }
        checked += 1;
    }
    assert!(checked >= 20, "only found {checked} examples in SKILL.md");
    assert!(
        failures.is_empty(),
        "SKILL.md examples that don't parse:\n  {}",
        failures.join("\n  ")
    );
}

fn read(path: &str) -> String {
    std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join(path)).unwrap()
}

/// Configuration is set up by people, not by the agent: the skill must not
/// teach it. The one rule telling the agent to leave it alone is allowed to
/// name the flags.
#[test]
fn skill_never_mentions_configuration() {
    const ALLOWED_RULE: &str = "don't pass `--config`, `--base-url` or `--ca-cert`";
    const FORBIDDEN: &[&str] = &[
        ".atlassian.toml",
        "--config",
        "--base-url",
        "--ca-cert",
        "base_url",
        "ca_cert",
        "username =",
        "password =",
        "[jira]",
        "[confluence]",
        "[bitbucket]",
    ];
    let skill = read(SKILL);
    assert!(
        skill.contains(ALLOWED_RULE),
        "SKILL.md should keep the rule: {ALLOWED_RULE}"
    );
    for (file, text) in [
        (SKILL, skill.replace(ALLOWED_RULE, "")),
        (REFERENCE, read(REFERENCE)),
    ] {
        let found: Vec<&&str> = FORBIDDEN.iter().filter(|f| text.contains(**f)).collect();
        assert!(
            found.is_empty(),
            "{file} mentions configuration, which the agent must not touch: {found:?}"
        );
    }
}
