#!/usr/bin/env python3
"""Convert Jira's HTML REST reference into a minimal OpenAPI 3 file.

Jira 9.x has no published OpenAPI spec; its reference is a single HTML page
(e.g. https://docs.atlassian.com/software/jira/docs/api/REST/9.12.0/) and the
WADL it links to is not served. This script keeps the GET operations from that
page: path, query parameters, success status, and the documented example (or
JSON schema) for the response. The test mock server only needs those.

Usage: jira-docs-to-openapi.py <docs.html> <version> <source-url> > specs/jira.json
"""

import html
import json
import re
import sys

METHOD = re.compile(r'<div class="method">(.*?)(?=<div class="method">|<div class="resource">|\Z)', re.S)
SIGNATURE = re.compile(r"<code>GET&nbsp;([^<]+)</code>")
QUERY_TABLE = re.compile(r"<h6>query parameters</h6><table[^>]*>(.*?)</table>", re.S)
PARAM = re.compile(r"<tr><td><code>([^<]+)</code></td>")
RESPONSE = re.compile(
    r'<span class="aui-lozenge aui-lozenge-success">Status\s*(\d+)</span></b>'
    r"(?: - <i>([^<]+)</i>)?(.*?)(?=</li>)",
    re.S,
)
BLOCK = re.compile(r"<h6>(Example|Schema)</h6><pre><code>(.*?)</code></pre>", re.S)


def parse_json(text):
    try:
        return json.loads(html.unescape(text))
    except ValueError:
        return None


def operation(body):
    params = []
    table = QUERY_TABLE.search(body)
    if table:
        for name in PARAM.findall(table.group(1)):
            params.append({"name": html.unescape(name), "in": "query", "schema": {"type": "string"}})

    responses = {}
    for status, media, rest in RESPONSE.findall(body):
        if status in responses:
            continue
        blocks = {kind: parse_json(text) for kind, text in BLOCK.findall(rest)}
        media_obj = {}
        if blocks.get("Example") is not None:
            media_obj["example"] = blocks["Example"]
        elif blocks.get("Schema") is not None:
            media_obj["schema"] = blocks["Schema"]
        resp = {"description": f"Status {status}"}
        if media and status != "204":
            resp["content"] = {media.strip(): media_obj}
        responses[status] = resp
        break  # first documented success response
    if not responses:
        responses["200"] = {"description": "No success response documented"}

    op = {"responses": responses}
    if params:
        op["parameters"] = params
    return op


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path, version, source = sys.argv[1:]
    page = open(path, encoding="utf-8").read()
    paths = {}
    for body in METHOD.findall(page):
        sig = SIGNATURE.search(body)
        if not sig:
            continue
        template = html.unescape(sig.group(1)).strip()
        paths.setdefault(template, {})["get"] = operation(body)
    spec = {
        "openapi": "3.0.1",
        "info": {
            "title": "Jira Data Center REST API (converted from the HTML reference)",
            "version": version,
            "description": f"Generated by scripts/jira-docs-to-openapi.py from {source}. "
            "GET operations only.",
        },
        "paths": dict(sorted(paths.items())),
    }
    json.dump(spec, sys.stdout, indent=1)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
